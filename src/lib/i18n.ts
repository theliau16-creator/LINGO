const DICTS: Record<string, Dict> = { fr, en, es, de, it, pt, nl };

export function translate(language: string | null | undefined, key: TranslationKey): string {
  const code = (language ?? "en").slice(0, 2).toLowerCase();
  return DICTS[code]?.[key] ?? en[key] ?? fr[key];
}

/** Renvoie la fonction de traduction liée à la langue du profil. */
export function useT() {
  const { data: profile } = useProfile();
  const language = profile?.primary_language ?? "en";
  const t = (key: TranslationKey) => translate(language, key);
  return { t, language };
}
